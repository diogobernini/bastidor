function resolveLang(preference, systemLocale) {
  if (preference === 'en' || preference === 'pt-BR') return preference;
  return String(systemLocale || '').toLowerCase().startsWith('pt') ? 'pt-BR' : 'en';
}

function makeT(lang) {
  const table = STRINGS[lang] || STRINGS.en;
  return (key, vars) => {
    let s = table[key] !== undefined ? table[key] : STRINGS.en[key] !== undefined ? STRINGS.en[key] : key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', String(v));
    }
    return s;
  };
}

module.exports = { STRINGS, resolveLang, makeT };
